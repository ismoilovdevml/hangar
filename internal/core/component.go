package core

import (
	"strings"
	"time"
)

// Component is a package version: payments-api:2.14.0, @acme/ui-kit@5.3.1,
// com.acme:ledger-core:7.0.0. It is unique per (repository, namespace, name, version).
type Component struct {
	ID           string `json:"id"`
	RepositoryID string `json:"repository_id"`
	// Repository is the repository name, filled on reads by the production service.
	Repository string `json:"repository,omitempty"`
	// Format is filled on reads by the production service from the owning repository.
	Format string `json:"format,omitempty"`

	// Namespace is the scope / group / organisation part of the coordinates:
	// npm scope ("@acme"), Maven groupId ("com.acme"), OCI image path prefix.
	// Empty when the format has none.
	Namespace string `json:"namespace"`
	Name      string `json:"name"`
	Version   string `json:"version"`

	CreatedAt   time.Time `json:"created_at"`
	PublishedBy string    `json:"published_by,omitempty"` // principal name

	LastDownloadedAt *time.Time `json:"last_downloaded_at,omitempty"`
	DownloadCount    int64      `json:"download_count"`
	Quarantined      bool       `json:"quarantined"`

	// Attributes are format-specific facts shown in the UI and used by search
	// (npm dist-tags, OCI platforms, Maven packaging, licence, source commit ...).
	Attributes map[string]any `json:"attributes,omitempty"`
}

// AssetKind separates published content from documents the format regenerates.
type AssetKind string

const (
	// AssetContent is immutable published content: jar, tgz, wheel, layer, manifest.
	AssetContent AssetKind = "content"
	// AssetMetadata is regenerated by the format (maven-metadata.xml, index.yaml,
	// packuments, checksum side files). Exempt from allow_once.
	AssetMetadata AssetKind = "metadata"
)

// Asset is a file in a repository, usually belonging to a component. Many assets
// (in any repositories of the same blob store) can point at one blob.
type Asset struct {
	ID           string `json:"id"`
	RepositoryID string `json:"repository_id"`
	// ComponentID is empty for assets that belong to no version
	// (repository-level metadata, raw files).
	ComponentID string `json:"component_id,omitempty"`

	// Path is the repository-relative path without a leading slash, exactly as
	// clients request it (e.g. "com/acme/ledger-core/7.0.0/ledger-core-7.0.0.jar").
	Path        string    `json:"path"`
	Kind        AssetKind `json:"kind"`
	BlobDigest  Digest    `json:"blob_digest"`
	ContentType string    `json:"content_type"`
	Size        int64     `json:"size"`
	// Checksums by algorithm name ("md5", "sha1", "sha256", "sha512"), hex encoded.
	// sha256 always equals BlobDigest.Hex().
	Checksums  map[string]string `json:"checksums,omitempty"`
	Attributes map[string]any    `json:"attributes,omitempty"`

	CreatedAt        time.Time  `json:"created_at"`
	UpdatedAt        time.Time  `json:"updated_at"`
	LastDownloadedAt *time.Time `json:"last_downloaded_at,omitempty"`
	DownloadCount    int64      `json:"download_count"`
}

// CleanPath normalises an asset path: no leading or trailing slash.
func CleanPath(p string) string { return strings.Trim(p, "/") }

// Coordinates identify a component for display and search. Formats fill the
// fields that apply; Extra carries anything else (classifier, platform, ...).
type Coordinates struct {
	Format    string            `json:"format"`
	Namespace string            `json:"namespace,omitempty"`
	Name      string            `json:"name"`
	Version   string            `json:"version,omitempty"`
	Extra     map[string]string `json:"extra,omitempty"`
}

// String renders "namespace/name@version" in a format-neutral way. Formats
// usually render their own idiom in the UI.
func (c Coordinates) String() string {
	var b strings.Builder
	if c.Namespace != "" {
		b.WriteString(c.Namespace)
		b.WriteByte('/')
	}
	b.WriteString(c.Name)
	if c.Version != "" {
		b.WriteByte('@')
		b.WriteString(c.Version)
	}
	return b.String()
}

// Page is one page of a list result. NextCursor is empty on the last page;
// pass it back as the query's Cursor to continue.
type Page[T any] struct {
	Items      []T    `json:"items"`
	NextCursor string `json:"next_cursor,omitempty"`
}

// DefaultPageSize and MaxPageSize bound list queries.
const (
	DefaultPageSize = 50
	MaxPageSize     = 1000
)

// ClampLimit applies DefaultPageSize and MaxPageSize to a requested limit.
func ClampLimit(n int) int {
	switch {
	case n <= 0:
		return DefaultPageSize
	case n > MaxPageSize:
		return MaxPageSize
	default:
		return n
	}
}
